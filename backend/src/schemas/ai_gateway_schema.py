"""
AI Gateway Schemas Module
Defines strict Pydantic v2 data contracts for our Three-Channel Resilient LLM Gateway,
tracking latency telemetry, active provider channels, and battle dialogue generations.
"""

from enum import Enum
from typing import Literal
from pydantic import BaseModel, Field


class LLMMessageRole(str, Enum):
    """
    Standard conversational roles for LLM interactions.
    Separates system-level referee personas from user coach instructions.
    """
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"


class LLMMessageItem(BaseModel):
    """
    Atomic dialogue turn within a multi-turn conversation or coaching prompt.
    """
    # The role of the entity transmitting this message
    role: LLMMessageRole = Field(
        default=LLMMessageRole.USER,
        description="Conversational role: system instructions, user input, or assistant reply",
    )
    # The text payload of the prompt or generated response
    content: str = Field(
        min_length=1,
        max_length=4000,
        description="The actual textual guidance or inquiry transmitted across the AI channel",
    )


class LLMCompletionRequest(BaseModel):
    """
    Generic intake payload for sending prompts to the Resilient LLM Gateway.
    Allows specifying prompt messages, temperature randomness, and token limits.
    """
    # Ordered sequence of conversation messages forming the tactical context
    messages: list[LLMMessageItem] = Field(
        min_length=1,
        description="Sequence of chat turns providing prompt instructions and context",
    )
    # Sampling temperature controlling creativity versus deterministic output
    temperature: float = Field(
        default=0.7,
        ge=0.0,
        le=2.0,
        description="Sampling temperature: 0.0 for deterministic output, up to 2.0 for expressive commentary",
    )
    # Upper bound on output token generation to guarantee swift battle-turn responses
    max_tokens: int = Field(
        default=250,
        ge=16,
        le=2048,
        description="Maximum token generation limit to prevent prolonged response latencies",
    )


class LLMResponseEnvelope(BaseModel):
    """
    Standardized battle envelope wrapping AI completions with full latency telemetry,
    active provider identification, and failover indicators.
    """
    # Identifies which channel successfully answered the call
    active_provider_name: Literal["ollama", "groq", "gemini", "offline_fallback"] = Field(
        description="Active provider that generated the completion: ollama, groq, gemini, or offline_fallback",
    )
    # Exact model name used by the responding provider
    model_identifier: str = Field(
        description="Model identifier such as qwen2.5:3b, qwen/qwen3.8-27b, or gemini-3.1-flash-lite",
    )
    # Wall-clock round-trip execution duration measured in milliseconds
    execution_latency_milliseconds: float = Field(
        ge=0.0,
        description="Round-trip request latency in milliseconds measured with high-precision time.perf_counter()",
    )
    # Flags whether the primary local channel failed and triggered secondary failovers
    fallback_triggered: bool = Field(
        default=False,
        description="True if primary local Ollama channel failed and fallback to Groq/Gemini was executed",
    )
    # The textual response generated by the AI model or offline fallback
    generated_message_content: str = Field(
        description="The textual completion returned by the active language model",
    )


class GameGuideGreetingRequest(BaseModel):
    """
    High-level request to awaken the Game Guide's AI Brain for a personalized greeting
    upon completing Trainer Registration.
    """
    # Validated trainer moniker entered on the registration card
    trainer_name: str = Field(
        min_length=2,
        max_length=20,
        description="Moniker of the newly registered tournament trainer",
    )
    # Selected starter monster identifier (1 = Bulbasaur, 4 = Charmander, 7 = Squirtle)
    selected_starter_id: int = Field(
        ge=1,
        le=7,
        description="Canonical Pokédex identifier of the player's chosen starter partner",
    )
    # Display name of the starter partner monster
    starter_monster_name: str = Field(
        min_length=1,
        max_length=50,
        description="Name of the selected starter monster (e.g. Charmander)",
    )
    # Elemental classification of the starter partner monster
    starter_elemental_type: str = Field(
        min_length=1,
        max_length=50,
        description="Primary elemental type of the monster (e.g. Fire, Water, Grass)",
    )


class ProviderHealthStatus(BaseModel):
    """
    Health diagnostic for an individual radio frequency channel in our gateway.
    """
    # Human-readable provider identifier (e.g. 'ollama', 'groq', 'gemini')
    provider_name: str = Field(
        description="Provider channel identifier: ollama, groq, or gemini",
    )
    # True if the channel is reachable and configured with valid credentials/endpoints
    is_available: bool = Field(
        description="Whether this provider channel is operational and reachable",
    )
    # Currently configured model string for this provider
    configured_model: str = Field(
        description="Target model identifier configured for this channel",
    )
    # Descriptive operational summary or outage explanation
    status_message: str = Field(
        description="Human-readable operational status or error message",
    )


class GatewayHealthResponse(BaseModel):
    """
    Diagnostic overview detailing the operational readiness of all three channels.
    """
    # Status reports across all three provider frequencies
    channels: list[ProviderHealthStatus] = Field(
        description="Diagnostic health reports for Ollama, Groq, and Gemini channels",
    )
    # The recommended channel that will be attempted first on subsequent turns
    recommended_active_channel: str = Field(
        description="Channel recommended for immediate battle completions",
    )